"""M1 check: the task set is solvable and the scorer discriminates (PLAN.md M1 exit).

    python -m eval.m1 [--seeds 5]

Over the scenario catalogue (every kind x variant x distractor, one task each per seed):
- reference trajectories (written from each task's setup) must all succeed;
- the hand-written runbook (sees only tool output + what a request says) must succeed;
- trivial strategies give the floor a model has to beat.
Writes results/summary/m1.json and m1.md.
"""

from __future__ import annotations

import argparse
import collections
import json
from datetime import datetime, timezone
from pathlib import Path

from baselines.runbook import RunbookPolicy
from executor.runner import Budget, ScriptedPolicy, run_episode
from executor.scorer import score
from tasks.generator.generate import all_scenarios, catalog
from tasks.generator.scenarios import KINDS
from tasks.tools import ALL_TOOLS, OUTCOMES

ROOT = Path(__file__).resolve().parents[1]


def rate(results: list[dict]) -> float:
    return round(sum(r["success"] for r in results) / len(results), 3)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    args = ap.parse_args()
    tasks = [t for s in range(args.seeds) for t in catalog(s)]
    budget = Budget()
    policies = {"reference (gold replay)": lambda t: ScriptedPolicy(t["gold"]),
                "runbook (observations only)": RunbookPolicy,
                **{f"always finish {o}": (lambda o: lambda t: ScriptedPolicy([["finish", {"outcome": o, "message": "-"}]]))(o)
                   for o in OUTCOMES},
                "restart all workers, claim resolved": lambda t: ScriptedPolicy(
                    [["restart_service", {"service": "worker"}], ["finish", {"outcome": "resolved", "message": "-"}]])}
    results = {name: [score(t, run_episode(t, make(t), budget)) for t in tasks] for name, make in policies.items()}
    by_kind = collections.defaultdict(dict)
    for name in ("reference (gold replay)", "runbook (observations only)"):
        groups = collections.defaultdict(list)
        for t, r in zip(tasks, results[name]):
            groups[t["kind"]].append(r)
        for kind, rs in groups.items():
            by_kind[kind][name] = f"{sum(r['success'] for r in rs)}/{len(rs)}"
    report = {"generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "seeds": args.seeds,
              "tasks": len(tasks), "scenarios": len(all_scenarios()), "kinds": len(KINDS), "tools": sorted(ALL_TOOLS),
              "budget": vars(budget) if hasattr(budget, "__dict__") else {"max_steps": budget.max_steps, "max_retries": budget.max_retries},
              "outcome_mix": dict(collections.Counter(t["spec"]["outcome"] for t in tasks)),
              "family_mix": dict(collections.Counter(t["family"] for t in tasks)),
              "success": {name: rate(rs) for name, rs in results.items()},
              "gold_steps_median": sorted(len(t["gold"]) for t in tasks)[len(tasks) // 2],
              "by_kind": dict(sorted(by_kind.items()))}
    out = ROOT / "results/summary"
    out.mkdir(parents=True, exist_ok=True)
    (out / "m1.json").write_text(json.dumps(report, indent=1))
    lines = [f"# M1: task set and scorer check", "",
             f"{report['tasks']} tasks = {report['scenarios']} scenarios (kind x variant x distractor) x {args.seeds} seeds; "
             f"{report['kinds']} kinds, {len(ALL_TOOLS)} tools. Generated by `python -m eval.m1`.", "",
             "| Policy | Success |", "| --- | --- |"]
    lines += [f"| {name} | {v:.1%} |" for name, v in report["success"].items()]
    lines += ["", f"Outcome mix: {report['outcome_mix']}. Median reference trajectory: {report['gold_steps_median']} calls.", "",
              "| Kind | Reference | Runbook |", "| --- | --- | --- |"]
    lines += [f"| {k} | {v['reference (gold replay)']} | {v['runbook (observations only)']} |" for k, v in report["by_kind"].items()]
    (out / "m1.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
